typedef struct { void *resv; HMODULE h; int refs; volatile int active; uint8_t *pool; char path[MAX_PATH]; } ModState;
static ModState mod_st[MAX_MODS];
static int mods_disabled;
static guest_fn mod_lookup(uint32_t va) {
    for (int i = 0; i < MAX_MODS && recomp_mods[i]; i++) {
        const RecompModDesc *d = recomp_mods[i];
        if (mod_st[i].active && va >= d->base && va < d->base + d->size) { guest_fn f = d->lookup(va); if (f) return f; }
    }
    return 0;
}
static int mod_of_handle(HMODULE h) {   /* index of a loaded recompiled module with this handle, or -1 */
    for (int i = 0; i < MAX_MODS && recomp_mods[i]; i++) if (h && mod_st[i].h == h) return i;
    return -1;
}
typedef struct { uint32_t va; const char *name; } SymEnt;   /* names from symbols/*.sym (host/gen_symtab.py) */
