/* ---- guarded allocator for lgvid.dll / ffmpeg.dll (their msvcrt malloc family is redirected here): canaries + padding, so a small
        overflow in a decoder is reported (with the allocating call site) instead of killing the process with a heap-corruption failure ---- */
typedef struct FFHdr { uint32_t magic, size, caller; struct FFHdr *prev, *next; uint32_t pad[3]; } FFHdr;   /* 32 bytes, sits right before the user block */
#define FF_MAGIC 0xF00DCAFEu
#define FF_FRONT 128u
#define FF_REAR 128u
static CRITICAL_SECTION ff_cs; static int ff_cs_init; static FFHdr *ff_head; static LONG ff_live, ff_reported;
static void ff_where(char *o, size_t n, uint32_t a) {
    HMODULE m; o[0] = 0;
    if (GetModuleHandleExA(GET_MODULE_HANDLE_EX_FLAG_FROM_ADDRESS | GET_MODULE_HANDLE_EX_FLAG_UNCHANGED_REFCOUNT, (LPCSTR)(uintptr_t)a, &m)) {
        char f[MAX_PATH]; GetModuleFileNameA(m, f, sizeof f); const char *b = strrchr(f, '\\'); snprintf(o, n, "%s+0x%x", b ? b + 1 : f, (unsigned)(a - (uint32_t)(uintptr_t)m));
    } else snprintf(o, n, "%08x", a);
}
static int ff_check(FFHdr *h, const char *when, uint32_t freer) {
    uint8_t *u = (uint8_t *)(h + 1), *base = u - FF_FRONT; int bad = 0; unsigned fi = 0, ri = 0, fcount = 0, rcount = 0;
    for (unsigned i = 0; i < FF_FRONT - sizeof(FFHdr); i++) if (base[i] != 0xAB) { if (!fcount++) fi = i; }
    for (unsigned i = 0; i < FF_REAR; i++) if (u[h->size + i] != 0xCD) { if (!rcount++) ri = i; }
    if (fcount || rcount) {
        bad = 1;
        if (InterlockedIncrement(&ff_reported) <= 60) {
            char w[160], w2[160]; ff_where(w, sizeof w, h->caller); ff_where(w2, sizeof w2, freer);
            hlog("FFMEM %s: block %p size=%u allocated from %s freed from %s: %u front bytes damaged (first at -%u), %u rear bytes damaged (first at +%u)",
                 when, u, h->size, w, w2, fcount, (unsigned)(FF_FRONT - fi - sizeof(FFHdr)) , rcount, ri);
        }
    }
    return bad;
}
static void *ff_malloc_c(size_t n, uint32_t caller) {
    if (!ff_cs_init) { InitializeCriticalSection(&ff_cs); ff_cs_init = 1; }
    uint8_t *b = (uint8_t *)malloc(FF_FRONT + n + FF_REAR); if (!b) return NULL;
    memset(b, 0xAB, FF_FRONT); memset(b + FF_FRONT + n, 0xCD, FF_REAR);
    FFHdr *h = (FFHdr *)(b + FF_FRONT - sizeof(FFHdr)); h->magic = FF_MAGIC; h->size = (uint32_t)n; h->caller = caller;
    EnterCriticalSection(&ff_cs); h->prev = NULL; h->next = ff_head; if (ff_head) ff_head->prev = h; ff_head = h; ff_live++; LeaveCriticalSection(&ff_cs);
    return h + 1;
}
static int ff_is(void *p) { return p && !IsBadReadPtr((uint8_t *)p - sizeof(FFHdr), sizeof(FFHdr)) && ((FFHdr *)p - 1)->magic == FF_MAGIC; }
static void ff_free_c(void *p, uint32_t caller) {
    if (!p) return;
    if (!ff_is(p)) {
        static LONG nf; BOOL ok = HeapValidate(GetProcessHeap(), 0, p); char w[160]; ff_where(w, sizeof w, caller);
        if (InterlockedIncrement(&nf) <= 80 || !ok) hlog("FFMEM free of non-guarded pointer %p from %s: %s", p, w, ok ? "valid heap block, freeing" : "NOT a valid heap block -> skipped (leaked)");
        if (ok) free(p);
        return;
    }
    FFHdr *h = (FFHdr *)p - 1; ff_check(h, "overflow found at free", caller);
    EnterCriticalSection(&ff_cs); if (h->prev) h->prev->next = h->next; else ff_head = h->next; if (h->next) h->next->prev = h->prev; ff_live--; LeaveCriticalSection(&ff_cs);
    h->magic = 0; free((uint8_t *)p - FF_FRONT);
}
static void *ff_malloc(size_t n) { return ff_malloc_c(n, (uint32_t)(uintptr_t)__builtin_return_address(0)); }
static void *ff_calloc(size_t a, size_t b) { void *p = ff_malloc_c(a * b, (uint32_t)(uintptr_t)__builtin_return_address(0)); if (p) memset(p, 0, a * b); return p; }
static void ff_free(void *p) { ff_free_c(p, (uint32_t)(uintptr_t)__builtin_return_address(0)); }
static void *ff_realloc(void *p, size_t n) {
    uint32_t ra = (uint32_t)(uintptr_t)__builtin_return_address(0);
    if (!p) return ff_malloc_c(n, ra);
    if (!n) { ff_free_c(p, ra); return NULL; }
    if (!ff_is(p)) { void *q = ff_malloc_c(n, ra); if (!q) return NULL; size_t o = _msize(p); memcpy(q, p, o < n ? o : n); free(p); return q; }
    FFHdr *h = (FFHdr *)p - 1; void *q = ff_malloc_c(n, ra); if (!q) return NULL;
    memcpy(q, p, h->size < n ? h->size : n); ff_free_c(p, ra); return q;
}
static void ff_check_all(const char *why) {
    if (!ff_cs_init) return;
    int bad = 0, tot = 0; EnterCriticalSection(&ff_cs);
    for (FFHdr *h = ff_head; h; h = h->next) { tot++; if (ff_check(h, why, 0)) bad++; }
    LeaveCriticalSection(&ff_cs);
    hlog("FFMEM sweep (%s): %d live guarded blocks, %d damaged", why, tot, bad);
}
static void patch_msvcrt_alloc(HMODULE m, const char *tag) {
    uint8_t *b = (uint8_t *)m; IMAGE_DOS_HEADER *dh = (IMAGE_DOS_HEADER *)b; IMAGE_NT_HEADERS *nt = (IMAGE_NT_HEADERS *)(b + dh->e_lfanew);
    DWORD rva = nt->OptionalHeader.DataDirectory[IMAGE_DIRECTORY_ENTRY_IMPORT].VirtualAddress; int np = 0;
    if (!rva) return;
    for (IMAGE_IMPORT_DESCRIPTOR *d = (IMAGE_IMPORT_DESCRIPTOR *)(b + rva); d->Name; d++) {
        const char *dn = (const char *)(b + d->Name); if (_stricmp(dn, "msvcrt.dll")) continue;
        IMAGE_THUNK_DATA *ot = (IMAGE_THUNK_DATA *)(b + (d->OriginalFirstThunk ? d->OriginalFirstThunk : d->FirstThunk)), *ft = (IMAGE_THUNK_DATA *)(b + d->FirstThunk);
        for (; ot->u1.AddressOfData; ot++, ft++) {
            if (ot->u1.Ordinal & 0x80000000u) continue;
            const char *fn = (const char *)((IMAGE_IMPORT_BY_NAME *)(b + ot->u1.AddressOfData))->Name; void *w = NULL;
            if (!strcmp(fn, "malloc")) w = (void *)ff_malloc; else if (!strcmp(fn, "calloc")) w = (void *)ff_calloc;
            else if (!strcmp(fn, "realloc")) w = (void *)ff_realloc; else if (!strcmp(fn, "free")) w = (void *)ff_free;
            if (w) { DWORD op; VirtualProtect(&ft->u1.Function, 4, PAGE_READWRITE, &op); ft->u1.Function = (DWORD)(uintptr_t)w; VirtualProtect(&ft->u1.Function, 4, op, &op); np++; }
        }
    }
    hlog("FFMEM: redirected %d msvcrt allocator imports in %s", np, tag);
}
