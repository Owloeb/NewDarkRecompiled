static void describe(char *out, size_t n, void *p) {
    HMODULE m;
    if (GetModuleHandleExA(GET_MODULE_HANDLE_EX_FLAG_FROM_ADDRESS | GET_MODULE_HANDLE_EX_FLAG_UNCHANGED_REFCOUNT, (LPCSTR)p, &m)) {
        char path[MAX_PATH]; GetModuleFileNameA(m, path, MAX_PATH);
        const char *b = strrchr(path, '\\');
        unsigned off = (unsigned)((char *)p - (char *)m);
        int len = snprintf(out, n, "%s+0x%x", b ? b + 1 : path, off);
        if ((uintptr_t)m == hd_base) {   /* game code: add the function's name if we have one */
            uint32_t st = fn_start((uint32_t)(uintptr_t)p); const char *nm = st ? sym_name(st) : NULL;
            if (nm && len > 0 && len < (int)n) len += snprintf(out + len, n - len, " (%s+0x%x)", nm, (unsigned)((uint32_t)(uintptr_t)p - st));
        }
        /* nearest named export at or below the address, if one is close */
        const IMAGE_DOS_HEADER *dh = (const IMAGE_DOS_HEADER *)m;
        const IMAGE_NT_HEADERS *nt = (const IMAGE_NT_HEADERS *)((const char *)m + dh->e_lfanew);
        const IMAGE_DATA_DIRECTORY *dd = &nt->OptionalHeader.DataDirectory[IMAGE_DIRECTORY_ENTRY_EXPORT];
        if (dd->VirtualAddress && (uintptr_t)m != hd_base) {
            const IMAGE_EXPORT_DIRECTORY *ex = (const IMAGE_EXPORT_DIRECTORY *)((const char *)m + dd->VirtualAddress);
            const DWORD *fn = (const DWORD *)((const char *)m + ex->AddressOfFunctions), *nm = (const DWORD *)((const char *)m + ex->AddressOfNames);
            const WORD *ord = (const WORD *)((const char *)m + ex->AddressOfNameOrdinals);
            unsigned bestd = 0x4000; const char *bn = NULL;
            for (DWORD i = 0; i < ex->NumberOfNames; i++) {
                DWORD rva = fn[ord[i]];
                if (rva <= off && off - rva < bestd) { bestd = off - rva; bn = (const char *)m + nm[i]; }
            }
            if (bn && (size_t)len < n) snprintf(out + len, n - len, " (~%s+0x%x)", bn, bestd);
        }
    } else snprintf(out, n, "%p", p);
}

