__asm__(
    ".text\n"
    ".globl _native_call\n"
    "_native_call:\n"
    "    pushl %ebp\n"
    "    movl %esp, %ebp\n"
    "    pushl %ebx\n"
    "    pushl %esi\n"
    "    pushl %edi\n"
    "    andl $-16, %esp\n"               /* native callees may assume 16-byte alignment at the call */
    "    movl 12(%ebp), %esi\n"           /* args */
    "    movl 16(%ebp), %ecx\n"           /* nargs */
    "    movl %ecx, %eax\n"
    "    shll $2, %eax\n"
    "    subl %eax, %esp\n"
    "    movl %esp, %edi\n"
    "    cld\n"
    "    rep movsl\n"
    "    movl %esp, %ebx\n"               /* args base: esp after the call == ebx + 4*bytes popped by callee */
    "    movl 20(%ebp), %ecx\n"           /* thiscall / fastcall */
    "    movl 24(%ebp), %edx\n"
    "    movl 8(%ebp), %eax\n"
    "    call *%eax\n"
    "    movl 28(%ebp), %edi\n"
    "    movl %eax, 0(%edi)\n"
    "    movl %edx, 4(%edi)\n"
    "    movl %esp, %ecx\n"
    "    subl %ebx, %ecx\n"
    "    movl %ecx, 8(%edi)\n"
    "    movl $0, 12(%edi)\n"
    "    fxam\n"
    "    fnstsw %ax\n"
    "    andw $0x4500, %ax\n"
    "    cmpw $0x4100, %ax\n"             /* C3=1 C2=0 C0=1: st(0) empty */
    "    je 1f\n"
    "    fstpl 16(%edi)\n"
    "    movl $1, 12(%edi)\n"
    "1:\n"
    "    leal -12(%ebp), %esp\n"
    "    popl %edi\n"
    "    popl %esi\n"
    "    popl %ebx\n"
    "    popl %ebp\n"
    "    ret\n"
    /* entered from a per-function stub: eax = guest address, native args at 4(%esp), ecx/edx as the caller left them */
    ".globl _cb_common\n"
    "_cb_common:\n"
    "    pushl %ebp\n"
    "    movl %esp, %ebp\n"
    "    pushl %ebx\n"
    "    pushl %esi\n"
    "    pushl %edi\n"
    "    subl $8, %esp\n"
    "    leal (%esp), %ebx\n"
    "    leal 8(%ebp), %esi\n"
    "    pushl %ebx\n"                    /* &popped */
    "    pushl %edx\n"
    "    pushl %ecx\n"
    "    pushl %esi\n"                    /* native args */
    "    pushl %eax\n"                    /* guest address */
    "    call _cb_dispatch\n"
    "    addl $20, %esp\n"
    "    movl (%esp), %ecx\n"             /* bytes the guest callee popped (stdcall) */
    "    movl 4(%esp), %edx\n"            /* the guest callee's edx: high half of a 64-bit return value */
    "    addl $8, %esp\n"
    "    popl %edi\n"
    "    popl %esi\n"
    "    popl %ebx\n"
    "    popl %ebp\n"
    /* esp -> return address. Move it to the last popped argument slot and `ret`, without needing a spare register. */
    "    leal (%esp,%ecx), %ecx\n"
    "    pushl (%esp)\n"
    "    popl (%ecx)\n"
    "    movl %ecx, %esp\n"
    "    ret\n"
);

uint32_t cb_dispatch(uint32_t addr, const uint32_t *nargs, uint32_t ecx, uint32_t edx, uint32_t *popped) {
    TC *t = get_tc(); CPU *c = &t->cpu;
    guest_fn f = nd_lookup(addr);
    if (!f) f = mod_lookup(addr);
    if (!f) die("native code called guest address %08x which is not a recompiled function", addr);
    CPU save = *c;
    uint32_t sp = t->depth ? c->esp : t->stk_hi - 64;
    sp -= 4 * NATIVE_K;
    memcpy((void *)(uintptr_t)sp, nargs, 4 * NATIVE_K);
    sp -= 4; *(uint32_t *)(uintptr_t)sp = 0xFEEDFACEu;      /* return address, never used */
    c->esp = sp; c->ecx = ecx; c->edx = edx; c->df = 0;
    if (!t->depth) { c->top = 0; c->cw = 0x27F; c->sw = 0; }
    int tr = 0; vid_ranges();
    if (g_debug && in_vid(nargs[-1]) && InterlockedIncrement(&g_cb_logged) <= 4000) {
        tr = 1;
        hlog("  CALLBACK from lgvid/ffmpeg (ret %08x) into guest %08x ecx=%08x edx=%08x args: %08x %08x %08x %08x %08x %08x", nargs[-1], addr, ecx, edx,
             nargs[0], nargs[1], nargs[2], nargs[3], nargs[4], nargs[5]);
    }
    if (tr && !heaps_valid()) hlog("  HEAP BAD on callback entry %08x (heap %p)", addr, (void *)hc_bad_heap);
    t->depth++;
    f(c);
    t->depth--;
    if (tr && !heaps_valid()) hlog("  HEAP BAD after callback %08x (heap %p)", addr, (void *)hc_bad_heap);
    if (tr) hlog("  CALLBACK %08x returns eax=%08x edx=%08x popped=%u", addr, c->eax, c->edx, (unsigned)(c->esp - sp - 4));
    uint32_t r = c->eax;
    *popped = c->esp - sp - 4;
    popped[1] = c->edx;
    *c = save;
    return r;
}

