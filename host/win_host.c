static void drain_newfn(const char *why) {
    unsigned end = rt_nseq; if (end - seq_done > 32768) seq_done = end - 32768;
    if (end == seq_done) return;
    hlog("NEWFN (%s): %u guest functions entered for the first time (total %u)", why, end - seq_done, end);
    char line[300]; int len = 0, cnt = 0;
    for (; seq_done < end; seq_done++) {
        const char *f = rt_seq[seq_done & 32767]; len += snprintf(line + len, sizeof line - len, "%s ", f ? f + 3 : "?");
        if (++cnt % 16 == 0) { hlog("   %s", line); len = 0; }
    }
    if (len) hlog("   %s", line);
}

#define IMPRING 512
typedef struct { int idx; void *fn; uint32_t a[4], ecx, ret, eax; LONG n; volatile int done; DWORD tid; } ImpRec;
static ImpRec imp_ring[IMPRING]; static volatile unsigned imp_ring_i;
static uintptr_t vid_lo[2], vid_hi[2];     /* address ranges of lgvid.dll and ffmpeg.dll, once loaded */
static void vid_ranges(void) {
    static const char *nm[2] = { "lgvid.dll", "ffmpeg.dll" };
    for (int i = 0; i < 2; i++) {
        HMODULE m = GetModuleHandleA(nm[i]); if (!m || vid_lo[i]) continue;
        const IMAGE_NT_HEADERS *nt = (const IMAGE_NT_HEADERS *)((const char *)m + ((const IMAGE_DOS_HEADER *)m)->e_lfanew);
        vid_lo[i] = (uintptr_t)m; vid_hi[i] = (uintptr_t)m + nt->OptionalHeader.SizeOfImage;
    }
}
static int in_vid(uintptr_t a) { return (a >= vid_lo[0] && a < vid_hi[0]) || (a >= vid_lo[1] && a < vid_hi[1]); }
static volatile LONG g_in_native, g_cb_logged;          /* number of call_native frames currently open (all threads) */
static ImpRec *imp_begin(CPU *c, void *fn, int idx, LONG n) {
    unsigned k = imp_ring_i++ % IMPRING; ImpRec *r = &imp_ring[k];
    const uint32_t *a = (const uint32_t *)(uintptr_t)(c->esp + 4);
    r->idx = idx; r->fn = fn; memcpy(r->a, a, 16); r->ecx = c->ecx; r->ret = a[-1]; r->n = n; r->done = 0; r->eax = 0; r->tid = GetCurrentThreadId();
    return r;
}

typedef struct { uint32_t buf, esp, ebp, ebx, esi, edi, fs0, val; int depth, used; void *hj[5]; } SjRec;   /* one guest setjmp */
#define SJ_MAX 32
typedef struct { CPU cpu; uint32_t stk_lo, stk_hi; int depth; SjRec sj[SJ_MAX]; unsigned sj_tick; } TC;
static DWORD tls_idx = TLS_OUT_OF_INDEXES;

static TC *get_tc(void) {
    TC *t = (TC *)TlsGetValue(tls_idx);
    if (!t) {
        t = (TC *)calloc(1, sizeof *t);
        void *stk = VirtualAlloc(NULL, GUEST_STACK + 0x10000, MEM_RESERVE | MEM_COMMIT, PAGE_READWRITE);
        if (!stk) { hlog("cannot allocate guest stack"); ExitProcess(2); }
        t->stk_lo = (uint32_t)(uintptr_t)stk; t->stk_hi = t->stk_lo + GUEST_STACK;
        t->cpu.cw = 0x27F;
        uint32_t teb; __asm__ volatile("movl %%fs:0x18, %0" : "=r"(teb));
        t->cpu.fs_base = teb;
        TlsSetValue(tls_idx, t);
    }
    return t;
}

