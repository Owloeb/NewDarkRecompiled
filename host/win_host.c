/* darkrecomp Windows host (32-bit, identity-mapped).
 *
 * Maps the retail SS2.exe image at its preferred base (guest address == host address), resolves its imports to the
 * real DLLs, then runs the recompiled entry point. Native code that calls back into the game (window procedures,
 * COM vtables, CRT init tables, thread starts) lands in the original bytes, whose first 5 bytes have been replaced by a
 * jump to a thunk that runs the *recompiled* function instead.
 *
 * Calls from the recompiled code to imports / native pointers copy the guest stack arguments onto the native stack,
 * call, and measure how many bytes the callee popped (stdcall vs cdecl needs no signature table).
 */
