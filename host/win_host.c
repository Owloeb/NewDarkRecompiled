static void dump_state(CPU *c, const char *why) {
    hlog("==== %s", why);
    if (c) hlog("eax=%08x ecx=%08x edx=%08x ebx=%08x esp=%08x ebp=%08x esi=%08x edi=%08x", c->eax, c->ecx, c->edx, c->ebx, c->esp, c->ebp, c->esi, c->edi);
    unsigned n = rt_ring_i; char line[512]; int len = 0; const char *prev = 0; int shown = 0;
    hlog("last guest functions / loop heads (oldest first):");
    for (unsigned k = (n > 4095 ? n - 4095 : 0); k < n; k++) {
        const char *f = rt_ring[k & 4095];
        if (f == prev) continue;
        prev = f;
        if (n - k > 120) continue;
        len += snprintf(line + len, sizeof line - len, "%s ", f ? f + 3 : "?");
        if (++shown % 8 == 0) { hlog("  %s", line); len = 0; }
    }
    if (len) hlog("  %s", line);
    {   /* the same, newest first, with names where known */
        const char *seen[12]; int ns = 0;
        for (unsigned k = n; k-- > (n > 4095 ? n - 4095 : 0) && ns < 12;) {
            const char *f = rt_ring[k & 4095]; int dup = 0;
            if (!f || strlen(f) < 11) continue;
            for (int q = 0; q < ns; q++) if (seen[q] == f) dup = 1;
            if (dup) continue;
            seen[ns++] = f;
            const char *nm = !strncmp(f, "nd_", 3) ? sym_name((uint32_t)strtoul(f + 3, NULL, 16)) : NULL;
            if (nm) hlog("    %s  %s", f + 3, nm);
        }
    }
    unsigned m = imp_ring_i; hlog("last native calls (oldest first; 'open' = entered, not yet returned), %ld call_native frames open:", (long)g_in_native);
    for (unsigned k = (m > 48 ? m - 48 : 0); k < m; k++) {
        ImpRec *r = &imp_ring[k % IMPRING]; char d[160];
        if (r->idx >= 0) snprintf(d, sizeof d, "%s!%s", hd_imports[r->idx].dll, hd_imports[r->idx].name); else describe(d, sizeof d, r->fn);
        hlog("  #%ld t%lu %s(%08x,%08x,%08x,%08x) ecx=%08x ret=%08x %s eax=%08x", r->n, r->tid, d, r->a[0], r->a[1], r->a[2], r->a[3], r->ecx, r->ret,
             r->done ? "done" : "OPEN", r->eax);
    }
}

static CPU *cur_cpu(void) { TC *t = (TC *)TlsGetValue(tls_idx); return t ? &t->cpu : NULL; }

static void die(const char *fmt, ...) {
    g_crash = 1;
    char buf[512]; va_list ap; va_start(ap, fmt); vsnprintf(buf, sizeof buf, fmt, ap); va_end(ap);
    dump_state(cur_cpu(), buf);
    MessageBoxA(NULL, buf, "darkrecomp: fatal", MB_OK | MB_ICONERROR | MB_TOPMOST);
    ExitProcess(1);
}

