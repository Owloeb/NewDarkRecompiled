/* original entry bytes -> jump to a stub -> cb_common -> recompiled function */
static void install_entry_hooks(void) {
    uint8_t *pool = (uint8_t *)VirtualAlloc(NULL, (size_t)nd_table_n * 10, MEM_RESERVE | MEM_COMMIT, PAGE_EXECUTE_READWRITE);
    if (!pool) die("cannot allocate entry stubs");
    unsigned patched = 0, tiny = 0, smc = 0;
    for (unsigned i = 0; i < nd_table_n; i++) {
        uint32_t e = nd_table[i].va, end = 0;
        for (unsigned k = 0; k < hd_ncode; k++) if (e >= hd_code_lo[k] && e < hd_code_hi[k]) end = hd_code_hi[k];
        uint32_t next = i + 1 < nd_table_n ? nd_table[i + 1].va : end;
        if (next > end) next = end;
        if (next < e + 5) { tiny++; continue; }
        int hit = 0;
        for (unsigned k = 0; k < hd_nsmc; k++) if (hd_smc_lo[k] < e + 5 && hd_smc_hi[k] > e) { hit = 1; break; }
        if (hit) { smc++; continue; }
        uint8_t *s = pool + (size_t)i * 10;
        s[0] = 0xB8; *(uint32_t *)(s + 1) = e;
        s[5] = 0xE9; *(int32_t *)(s + 6) = (int32_t)((uint8_t *)cb_common - (s + 10));
        uint8_t *p = (uint8_t *)(uintptr_t)e;
        p[0] = 0xE9; *(int32_t *)(p + 1) = (int32_t)(s - (p + 5));
        patched++;
    }
    hlog("entry hooks: %u patched, %u too small, %u overlap patch fields (left as original code)", patched, tiny, smc);
}

/* ---- recompiled DLLs (allobjs.osm) ----
   The engine loads script modules with LoadLibraryA and unloads them with FreeLibrary on every mission change. For a module we
   have recompiled, the host maps the real file itself at its preferred base WITHOUT running its DllMain or binding imports
   (DONT_RESOLVE_DLL_REFERENCES), checks that its code is byte-identical to what was lifted, binds the imports (through the
   same wrappers the exe uses), sends every function entry to the recompiled code, and then runs DllMain - recompiled too.
   If anything doesn't match (a mod ships its own allobjs.osm, the address is taken, ...) the original DLL is used as before. */
static void hook_code(const rc_ent *tab, unsigned n, const uint32_t *lo, const uint32_t *hi, unsigned nr, uint8_t **poolp, const char *what) {
    if (!*poolp) *poolp = (uint8_t *)VirtualAlloc(NULL, (size_t)n * 10, MEM_RESERVE | MEM_COMMIT, PAGE_EXECUTE_READWRITE);
    uint8_t *pool = *poolp; if (!pool) die("cannot allocate entry stubs for %s", what);
    unsigned patched = 0, tiny = 0;
    for (unsigned r = 0; r < nr; r++) { DWORD op; VirtualProtect((void *)(uintptr_t)lo[r], hi[r] - lo[r], PAGE_EXECUTE_READWRITE, &op); }
    for (unsigned i = 0; i < n; i++) {
        uint32_t e = tab[i].va, end = 0;
        for (unsigned k = 0; k < nr; k++) if (e >= lo[k] && e < hi[k]) end = hi[k];
        if (!end) continue;
        uint32_t next = i + 1 < n ? tab[i + 1].va : end; if (next > end) next = end;
        if (next < e + 5) { tiny++; continue; }
        uint8_t *s = pool + (size_t)i * 10;
        s[0] = 0xB8; *(uint32_t *)(s + 1) = e;
        s[5] = 0xE9; *(int32_t *)(s + 6) = (int32_t)((uint8_t *)cb_common - (s + 10));
        uint8_t *p = (uint8_t *)(uintptr_t)e;
        p[0] = 0xE9; *(int32_t *)(p + 1) = (int32_t)(s - (p + 5));
        patched++;
    }
    FlushInstructionCache(GetCurrentProcess(), NULL, 0);
    hlog("%s: %u entry points redirected to recompiled code, %u too small", what, patched, tiny);
}
static void mod_reserve(int k) {
    const RecompModDesc *d = recomp_mods[k];
    if (!mod_st[k].resv && !mod_st[k].h) mod_st[k].resv = VirtualAlloc((void *)(uintptr_t)d->base, d->size, MEM_RESERVE, PAGE_NOACCESS);
}
static uint32_t code_crc(const RecompModDesc *d) {   /* crc32 over all code ranges, chained like zlib.crc32 */
    static uint32_t tab[256]; uint32_t crc = 0;
    if (!tab[1]) for (uint32_t i = 0; i < 256; i++) { uint32_t c = i; for (int k = 0; k < 8; k++) c = c & 1 ? 0xEDB88320u ^ (c >> 1) : c >> 1; tab[i] = c; }
    for (unsigned r = 0; r < d->ncode; r++) {
        const uint8_t *q = (const uint8_t *)(uintptr_t)d->code_lo[r]; size_t len = d->code_hi[r] - d->code_lo[r];
        uint32_t c = ~crc; while (len--) c = tab[(c ^ *q++) & 0xFF] ^ (c >> 8); crc = ~c;
    }
    return crc;
}
/* Map a DLL file at d->base ourselves: headers, sections, base relocations. Returns the base or NULL (why set). */
static uint8_t *map_manual(const RecompModDesc *d, const char *path, const char **why) {
    HANDLE fh = CreateFileA(path, GENERIC_READ, FILE_SHARE_READ, NULL, OPEN_EXISTING, 0, NULL);
    if (fh == INVALID_HANDLE_VALUE) { *why = "could not be opened"; return NULL; }
    DWORD sz = GetFileSize(fh, NULL), got = 0; uint8_t *f = (uint8_t *)malloc(sz ? sz : 1);
    BOOL ok = f && ReadFile(fh, f, sz, &got, NULL) && got == sz; CloseHandle(fh);
    if (!ok || sz < 0x400) { free(f); *why = "could not be read"; return NULL; }
    IMAGE_NT_HEADERS *nt = (IMAGE_NT_HEADERS *)(f + ((IMAGE_DOS_HEADER *)f)->e_lfanew);
    if (nt->OptionalHeader.SizeOfImage != d->size || nt->OptionalHeader.ImageBase != d->file_base) { free(f); *why = "is a different version than the one that was recompiled (a mod's copy?)"; return NULL; }
    uint8_t *b = (uint8_t *)VirtualAlloc((void *)(uintptr_t)d->base, d->size, MEM_RESERVE | MEM_COMMIT, PAGE_EXECUTE_READWRITE);
    if (b != (uint8_t *)(uintptr_t)d->base) { if (b) VirtualFree(b, 0, MEM_RELEASE); free(f); *why = "could not get its address range"; return NULL; }
    memcpy(b, f, nt->OptionalHeader.SizeOfHeaders);
    IMAGE_SECTION_HEADER *sh = IMAGE_FIRST_SECTION(nt);
    for (unsigned i = 0; i < nt->FileHeader.NumberOfSections; i++) {
        DWORD n = sh[i].SizeOfRawData; if (sh[i].Misc.VirtualSize && n > sh[i].Misc.VirtualSize) n = sh[i].Misc.VirtualSize;
        if (sh[i].PointerToRawData + n <= sz && sh[i].VirtualAddress + n <= d->size) memcpy(b + sh[i].VirtualAddress, f + sh[i].PointerToRawData, n);
    }
    free(f);
    nt = (IMAGE_NT_HEADERS *)(b + ((IMAGE_DOS_HEADER *)b)->e_lfanew);
    uint32_t delta = d->base - nt->OptionalHeader.ImageBase;
    IMAGE_DATA_DIRECTORY *rd = &nt->OptionalHeader.DataDirectory[IMAGE_DIRECTORY_ENTRY_BASERELOC];
    if (delta && rd->VirtualAddress) {
        for (uint8_t *p = b + rd->VirtualAddress, *e = p + rd->Size; p < e;) {
            IMAGE_BASE_RELOCATION *blk = (IMAGE_BASE_RELOCATION *)p; if (!blk->SizeOfBlock) break;
            WORD *ent = (WORD *)(blk + 1); unsigned cnt = (blk->SizeOfBlock - sizeof *blk) / 2;
            for (unsigned k = 0; k < cnt; k++) if ((ent[k] >> 12) == IMAGE_REL_BASED_HIGHLOW) *(uint32_t *)(b + blk->VirtualAddress + (ent[k] & 0xFFF)) += delta;
            p += blk->SizeOfBlock;
        }
    }
    nt->OptionalHeader.ImageBase = d->base;
    return b;
}
static FARPROC mod_export(HMODULE h, LPCSTR n) {   /* GetProcAddress for a module the host mapped itself */
    uint8_t *b = (uint8_t *)h; IMAGE_NT_HEADERS *nt = (IMAGE_NT_HEADERS *)(b + ((IMAGE_DOS_HEADER *)b)->e_lfanew);
    IMAGE_DATA_DIRECTORY *dd = &nt->OptionalHeader.DataDirectory[IMAGE_DIRECTORY_ENTRY_EXPORT];
    if (!dd->VirtualAddress) return NULL;
    IMAGE_EXPORT_DIRECTORY *ex = (IMAGE_EXPORT_DIRECTORY *)(b + dd->VirtualAddress);
    DWORD *fn = (DWORD *)(b + ex->AddressOfFunctions), *nm = (DWORD *)(b + ex->AddressOfNames); WORD *ord = (WORD *)(b + ex->AddressOfNameOrdinals);
    if ((uintptr_t)n <= 0xFFFF) { DWORD i = (DWORD)(uintptr_t)n - ex->Base; return i < ex->NumberOfFunctions ? (FARPROC)(b + fn[i]) : NULL; }
    for (DWORD i = 0; i < ex->NumberOfNames; i++) if (!strcmp((const char *)(b + nm[i]), n)) return (FARPROC)(b + fn[ord[i]]);
    SetLastError(ERROR_PROC_NOT_FOUND); return NULL;
}
static void bind_imports(uint8_t *base, int *nbound) {   /* like the Windows loader, through the exe's import wrappers where we have one */
    IMAGE_NT_HEADERS *nt = (IMAGE_NT_HEADERS *)(base + ((IMAGE_DOS_HEADER *)base)->e_lfanew);
    DWORD irva = nt->OptionalHeader.DataDirectory[IMAGE_DIRECTORY_ENTRY_IMPORT].VirtualAddress; int nb = 0;
    for (IMAGE_IMPORT_DESCRIPTOR *d = (IMAGE_IMPORT_DESCRIPTOR *)(base + irva); irva && d->Name; d++) {
        HMODULE dm = LoadLibraryA((const char *)(base + d->Name));
        IMAGE_THUNK_DATA *ot = (IMAGE_THUNK_DATA *)(base + (d->OriginalFirstThunk ? d->OriginalFirstThunk : d->FirstThunk)), *ft = (IMAGE_THUNK_DATA *)(base + d->FirstThunk);
        for (; ot->u1.AddressOfData; ot++, ft++) {
            void *p;
            if (ot->u1.Ordinal & 0x80000000u) p = dm ? (void *)GetProcAddress(dm, (LPCSTR)(uintptr_t)(ot->u1.Ordinal & 0xFFFF)) : NULL;
            else {
                const char *fn = (const char *)((IMAGE_IMPORT_BY_NAME *)(base + ot->u1.AddressOfData))->Name; p = dm ? (void *)GetProcAddress(dm, fn) : NULL;
                void *hk = hook_for(fn); if (hk && p) p = hk;
                ci_register(fn, p);   /* MSVC x87 intrinsics (_CIsin, ...) take their argument on the x87 stack: emulated */
            }
            if (!p) p = (void *)missing_import;
            DWORD op; VirtualProtect(&ft->u1.Function, 4, PAGE_READWRITE, &op); ft->u1.Function = (DWORD)(uintptr_t)p; VirtualProtect(&ft->u1.Function, 4, op, &op); nb++;
        }
    }
    *nbound = nb;
}
/* The engine loads script modules with LoadLibraryA and unloads them with FreeLibrary on every mission change. For a
   module we have recompiled, the host loads the file itself without running its DllMain (at its preferred base through
   Windows with DONT_RESOLVE_DLL_REFERENCES, or - for modules lifted rebased - mapped and relocated by the host), checks
   that its code is byte-identical to what was lifted, binds its imports, sends every function entry to the recompiled
   code, and then runs DllMain - recompiled too. On any mismatch (a mod ships its own copy, the address is taken, ...)
   the original DLL is used as before. */
static HMODULE mod_try_load(LPCSTR n) {
    if (mods_disabled || (uintptr_t)n <= 0xFFFF) return NULL;
    const char *b = strrchr(n, '\\'), *b2 = strrchr(n, '/'); if (b2 > b) b = b2; b = b ? b + 1 : n;
    int k = -1;
    for (int i = 0; i < MAX_MODS && recomp_mods[i]; i++) if (!_stricmp(b, recomp_mods[i]->name)) { k = i; break; }
    if (k < 0) return NULL;
    const RecompModDesc *d = recomp_mods[k]; ModState *st = &mod_st[k];
    if (st->h) { st->refs++; return st->h; }
    if (st->resv) { VirtualFree(st->resv, 0, MEM_RELEASE); st->resv = NULL; }
    const char *why = NULL; HMODULE h = NULL;
    if (d->manual) h = (HMODULE)map_manual(d, n, &why);
    else {
        h = LoadLibraryExA(n, NULL, DONT_RESOLVE_DLL_REFERENCES);
        if (!h) why = "could not be mapped";
        else if ((uintptr_t)h != d->base) why = "did not get its preferred address";
    }
    if (!why && code_crc(d) != d->crc) why = "is a different version than the one that was recompiled (a mod's copy?)";
    if (why) {
        hlog("RECOMP %s %s: using the original DLL", n, why);
        if (h) { if (d->manual) VirtualFree(h, 0, MEM_RELEASE); else FreeLibrary(h); }
        mod_reserve(k); return NULL;
    }
    int nb = 0; bind_imports((uint8_t *)h, &nb);
    hook_code(d->table, *d->table_n, d->code_lo, d->code_hi, d->ncode, &st->pool, d->name);
    snprintf(st->path, sizeof st->path, "%s", n);
    st->h = h; st->refs = 1; st->active = 1;
    BOOL ok = ((BOOL (WINAPI *)(HINSTANCE, DWORD, LPVOID))(uintptr_t)d->entry)((HINSTANCE)h, DLL_PROCESS_ATTACH, NULL);
    hlog("RECOMP %s: loaded the recompiled module%s (%d imports bound), DllMain -> %d", n, d->manual ? " (mapped by the host)" : "", nb, ok);
    if (!ok) {
        st->active = 0; st->h = NULL; st->refs = 0;
        if (d->manual) VirtualFree(h, 0, MEM_RELEASE); else FreeLibrary(h);
        mod_reserve(k); SetLastError(ERROR_DLL_INIT_FAILED); return NULL;
    }
    return h;
}
static int mod_try_free(HMODULE h) {
    int k = mod_of_handle(h); if (k < 0) return 0;
    const RecompModDesc *d = recomp_mods[k]; ModState *st = &mod_st[k];
    if (--st->refs > 0) return 1;
    ((BOOL (WINAPI *)(HINSTANCE, DWORD, LPVOID))(uintptr_t)d->entry)((HINSTANCE)h, DLL_PROCESS_DETACH, NULL);
    st->active = 0; st->h = NULL;
    if (d->manual) VirtualFree(h, 0, MEM_RELEASE); else FreeLibrary(h);
    mod_reserve(k);
    return 1;
}

